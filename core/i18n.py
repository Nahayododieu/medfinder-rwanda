def get_lang(request):
    lang = request.session.get('lang', DEFAULT_LANG) if hasattr(request, 'session') else DEFAULT_LANG
    return lang if lang in STRINGS else DEFAULT_LANG


def strings_for(lang):
    merged = dict(STRINGS[DEFAULT_LANG])
    merged.update(STRINGS.get(lang, {}))
    return merged


def language_context(request):
    from django.conf import settings
    lang = get_lang(request)
    current = next(item for item in LANGUAGE_MENU if item[0] == lang)
    return {'T': strings_for(lang), 'lang': lang, 'languages': LANGUAGES,
            'language_menu': LANGUAGE_MENU, 'current_language': current,
            'ussd_code': settings.USSD_CODE, 'hold_hours': settings.RESERVATION_HOLD_HOURS,
            'biz': {
                'whatsapp': ''.join(ch for ch in (settings.SUPPORT_WHATSAPP or settings.SUPPORT_PHONE) if ch.isdigit()),
                'social': settings.SOCIAL_LINKS,
                'name': settings.BUSINESS_NAME,
                'owner': settings.BUSINESS_OWNER,
                'rdb': settings.BUSINESS_RDB_NUMBER,
                'phone': settings.SUPPORT_PHONE,
                'email': settings.SUPPORT_EMAIL,
                'trial_days': settings.FREE_TRIAL_DAYS,
                'price': settings.SUBSCRIPTION_PRICE_RWF,
                'commission_pct': round(settings.PLATFORM_COMMISSION_RATE * 100, 1),
            }}
